"""Extract six disjoint, unchanged YaHei outline groups for 慢！. No font redistribution."""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools/_vendor'))
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import DecomposingRecordingPen, RecordingPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

source = Path('C:/Windows/Fonts/msyh.ttc')
font = TTFont(source, fontNumber=0)
glyph_set = font.getGlyphSet()

def contours(character):
    pen = DecomposingRecordingPen(glyph_set)
    glyph_set[font.getBestCmap()[ord(character)]].draw(pen)
    result, current = [], []
    for command in pen.value:
        current.append(command)
        if command[0] in ('closePath', 'endPath'):
            p = RecordingPen()
            p.value = current
            bounds = BoundsPen(glyph_set)
            p.replay(bounds)
            result.append((p, bounds.bounds))
            current = []
    assert not current
    return result

slow, punctuation = contours('慢'), contours('！')
assert len(slow) == 11 and len(punctuation) == 2
groups = [[], [], [], [], [], []]
for pen, bounds in slow:
    x0, y0, x1, y1 = bounds
    # Classify whole contours, including counters, along the existing component gaps.
    part = 0 if x0 < 500 else 1 if y0 >= 1000 else 2 if y0 >= 460 else 3
    groups[part].append((pen, bounds, 0))
shift = max(b[2] for _, b in slow) + 160 - min(b[0] for _, b in punctuation)
for pen, bounds in punctuation:
    groups[4 if bounds[1] > 300 else 5].append((pen, bounds, shift))
assert [len(g) for g in groups] == [2, 3, 4, 2, 1, 1]
x0 = min(b[0] + shift for group in groups for _, b, shift in group)
x1 = max(b[2] + shift for group in groups for _, b, shift in group)
y0 = min(b[1] for group in groups for _, b, _ in group)
y1 = max(b[3] for group in groups for _, b, _ in group)
parts = []
for index, (label, group) in enumerate(zip(['忄', '日', '罒', '又', '！竖笔', '！圆点'], groups)):
    pen = SVGPathPen(glyph_set)
    for contour, _, shift in group:
        contour.replay(TransformPen(pen, (1, 0, 0, -1, shift-x0, y1)))
    left, right = min(b[0]+s-x0 for _, b, s in group), max(b[2]+s-x0 for _, b, s in group)
    top, bottom = min(y1-b[3] for _, b, _ in group), max(y1-b[1] for _, b, _ in group)
    parts.append({'id': index, 'label': label, 'path': pen.getCommands(), 'contours': len(group),
                  'pivot': [(left+right)/2, (top+bottom)/2], 'width': right-left, 'height': bottom-top})
asset = {'text': '慢！', 'fontFamily': font['name'].getDebugName(1), 'fontStyle': font['name'].getDebugName(2),
         'fontSource': source.name, 'fontSha256': hashlib.sha256(source.read_bytes()).hexdigest(),
         'width': x1-x0, 'height': y1-y0, 'path': ''.join(p['path'] for p in parts), 'parts': parts}
(ROOT/'dist/assets/bomb-glyph.json').write_text(json.dumps(asset, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
metrics = {k: asset[k] for k in ['width', 'height']}
metrics['ratio'] = asset['width']/asset['height']
metrics['parts'] = [{k: p[k] for k in ['id', 'label', 'pivot', 'width', 'height']} for p in parts]
(ROOT/'dist/bomb-metrics.js').write_text('// Generated by tools/extract_bomb.py. Original outline component bounds.\nexport const BOMB_GLYPH=Object.freeze('+json.dumps(metrics, ensure_ascii=False)+');\n', encoding='utf-8')
print(json.dumps({'parts': [p['label'] for p in parts], 'contours': sum(p['contours'] for p in parts), 'ratio': metrics['ratio']}, ensure_ascii=False))
