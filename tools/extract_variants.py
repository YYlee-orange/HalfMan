"""Extract only U+66FC outlines; no font files or preview images are distributed."""
import json
import hashlib
import math
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent / '_vendor'))
from fontTools.ttLib import TTFont
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

sources = [('yahei', '微软雅黑', 'msyh.ttc'), ('simsun', '宋体', 'simsun.ttc'), ('youyuan', '幼圆', 'SIMYOU.TTF')]
glyphs = []
for ident, label, filename in sources:
    source = Path('C:/Windows/Fonts') / filename
    font = TTFont(source, fontNumber=0)
    glyph_set = font.getGlyphSet()
    glyph = glyph_set[font.getBestCmap()[0x66FC]]
    bounds = BoundsPen(glyph_set)
    glyph.draw(bounds)
    x0, y0, x1, y1 = bounds.bounds
    width, height = x1-x0, y1-y0
    pen = SVGPathPen(glyph_set)
    glyph.draw(TransformPen(pen, (1, 0, 0, -1, -x0, y1)))
    split = width/2
    halves = [{'side': side, 'clip': [x, 0, split, height], 'pivot': [x+split/2, height/2],
               'rotation': -math.pi/2, 'flipY': side == 'left'}
              for side, x in [('left', 0), ('right', split)]]
    assert halves[0]['clip'][2]+halves[1]['clip'][2] == width
    glyphs.append({'id': ident, 'label': label, 'fontFamily': font['name'].getDebugName(1),
                   'fontStyle': font['name'].getDebugName(2), 'fontSource': filename,
                   'fontSha256': hashlib.sha256(source.read_bytes()).hexdigest(),
                   'width': width, 'height': height, 'path': pen.getCommands(), 'splitX': split,
                   'halves': halves})

asset = ROOT / 'dist/assets/glyphs.json'
asset.write_text(json.dumps({'glyphs': glyphs}, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
metrics = [{'id': g['id'], 'label': g['label'], 'ratio': g['width']/g['height']} for g in glyphs]
(ROOT / 'dist/glyph-metrics.js').write_text('// Generated by tools/extract_variants.py.\nexport const FONT_SPECS = Object.freeze('+json.dumps(metrics, ensure_ascii=False)+');\n', encoding='utf-8')
print(json.dumps({'fonts': metrics, 'outlines': len({g['path'] for g in glyphs}), 'halfCoverage': 'exact disjoint halves of each original outline'}, ensure_ascii=False))
